// The dump holds each 32-bit word in the other byte order than guest memory
// (measured: the unswapped pattern never matched, the swapped one did), so both
// layouts are searched; in the swapped one byte k of a word sits at 3 - k.
size_t Swap(size_t i) { return (i & ~size_t(3)) + (3 - (i & 3)); }

// Scans guest memory for every target not yet in `done` (bit per target) and
// returns the updated mask. Each pass reads gigabytes, so it only runs until all
// targets are patched (the title's shader cache stays resident; patched bytes
// persist).
uint32_t ScanAndPatch(uint8_t* membase, uint32_t done) {
  size_t patched = 0;
  for (size_t ti = 0; ti < sizeof(kTargets) / sizeof(kTargets[0]); ++ti) {
    if (done & (1u << ti)) continue;
    const Target& t = kTargets[ti];
    for (int swap = 0; swap < 2; ++swap) {
      std::vector<uint8_t> pat(t.ucode, t.ucode + t.size);
      if (swap) {
        for (size_t i = 0; i < t.size; ++i) pat[Swap(i)] = t.ucode[i];
      }
      const std::boyer_moore_horspool_searcher search(pat.begin(), pat.end());
      uint8_t* p = membase;
      uint8_t* const end = membase + 0x100000000ULL;
      MEMORY_BASIC_INFORMATION mbi{};
      while (p < end && VirtualQuery(p, &mbi, sizeof(mbi))) {
        uint8_t* region = static_cast<uint8_t*>(mbi.BaseAddress);
        uint8_t* region_end = region + mbi.RegionSize;
        const DWORD prot = mbi.Protect & 0xFF;
        if (mbi.State == MEM_COMMIT && !(mbi.Protect & PAGE_GUARD) &&
            (prot == PAGE_READWRITE || prot == PAGE_EXECUTE_READWRITE)) {
          uint8_t* it = region;
          while ((it = std::search(it, region_end, search)) != region_end) {
            for (size_t e = 0; e < t.edit_count; ++e) {
              it[swap ? Swap(t.edits[e].at) : t.edits[e].at] = t.edits[e].to;
            }
            ++patched;
            done |= 1u << ti;
            REXLOG_WARN("BLURKILL patched {} at guest {:08x}", t.name,
                        static_cast<uint32_t>(it - membase));
            it += t.size;
          }
        }
        p = region_end;
      }
    }
  }
  (void)patched;
  return done;
}

